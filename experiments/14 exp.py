grammer={
    'S':['NP','VP'],
    'NP':['DET N'],
    'VP':['V'],
    'DET':["The"],
    'N_singular':["boy","girl","student"],
    'N_plural':["boys","girls","students"],
    "V_singular":["runs","plays","eats"],
    "V_plural":["run","play","eat"]
}
def c_agreement(sentence):
  words=sentence.lower().split()
  if len(words)!=3:
    return "the sentence length is not 3 so rejected"
  d,n,v=words
  if n in grammer['N_singular'] and v in grammer['V_singular']:
    return "accept the sentence singular"
  if n in grammer['N_plural'] and v in grammer['V_plural']:
    return "accept the plural sentence"
  else:
    return "reject the sentence"


sentences=["the boy runs","the boys run","the girl eats","the girls eat","the student plays","the students play"]
for sentence in sentences:
  print(sentence,"->",c_agreement(sentence))

